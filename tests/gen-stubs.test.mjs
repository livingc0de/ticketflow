    const plan = planWrites(new Map([['a', stub], ['b', stub], ['c', stub], ['m.json', '{}\n']]), new Map([['b', stub], ['c', 'hand-written'], ['old.toml', '# Generated by ticketflow gen-stubs from y.\n'], ['own', 'mine'], ['m.json', '{"x":1}\n']]))

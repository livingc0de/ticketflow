test('two runs are byte-identical and input order does not matter', () => {
    const cfg = config(AGENTS)
    const parse = (t, p) => ({ ...parseCanonical(t, p), src: p })
    const skills = [parse(SKILL, 'skills/demo/SKILL.md'), parse(SKILL.replaceAll('demo', 'other'), 'skills/other/SKILL.md')]
    const roles = [parse(ROLE, 'agents/judge.md')]
    const args = { adapters: [adapter('claude'), adapter('codex')], cfg, runtimeRel: '.ticketflow' }
    const a = renderStubs({ ...args, skills, roles })
    const b = renderStubs({ ...args, skills: [...skills].reverse(), roles, adapters: [adapter('codex'), adapter('claude')] })
    assert.deepEqual([...a], [...b])
    assert.deepEqual([...a.keys()], [...a.keys()].sort())
    const t = setup()
    run(t)
    const before = ['.claude/agents/judge.md', '.codex/agents/judge.toml'].map((p) => t.read(p))
    run(t)
    assert.deepEqual(['.claude/agents/judge.md', '.codex/agents/judge.toml'].map((p) => t.read(p)), before)
})

test('--check: clean 0; an edited, a missing and a stale stub exit 1 and are named; write mode repairs them', () => {
    const t = setup()
    assert.equal(run(t, '--check').status, 1)   // nothing written yet
    run(t)
    const clean = run(t, '--check')
    assert.equal(clean.status, 0, clean.stdout)
    t.put('.claude/agents/judge.md', t.read('.claude/agents/judge.md') + 'edit\n')
    let r = run(t, '--check')
    assert.equal(r.status, 1); assert.match(r.stdout, /out of date: \.claude\/agents\/judge\.md/)
    run(t)
    assert.equal(run(t, '--check').status, 0)
    rmFile(t, '.agents/skills/demo/SKILL.md')
    r = run(t, '--check')
    assert.equal(r.status, 1); assert.match(r.stdout, /\.agents\/skills\/demo\/SKILL\.md/)
    run(t)
    rmFile(t, '.ticketflow/agents/judge.md')
    r = run(t, '--check')
    assert.equal(r.status, 1); assert.match(r.stdout, /stale: \.claude\/agents\/judge\.md/); assert.match(r.stdout, /stale: \.codex\/agents\/judge\.toml/)
    assert.equal(run(t).status, 0)
    assert.ok(!t.has('.claude/agents/judge.md') && !t.has('.codex/agents/judge.toml'))
})


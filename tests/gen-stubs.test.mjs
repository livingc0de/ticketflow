import test from 'node:test'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, rmSync, symlinkSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { parseCanonical, planWrites, renderStubs, StubError } from '../core/lib/stubs.mjs'
import { config, rawConfig, tempDir } from './helpers.mjs'

const script = new URL('../core/scripts/gen-stubs.mjs', import.meta.url).pathname
const adapter = (name) => ({ name, ...JSON.parse(readFileSync(new URL(`../core/adapters/${name}.json`, import.meta.url), 'utf8')) })
const MODELS = { claude: { strong: 'opus', standard: 'sonnet', light: 'haiku' }, codex: { strong: null, standard: 'gpt-x', light: null } }
const AGENTS = { agents: ['claude', 'codex'], models: MODELS }

const SKILL = '---\nname: demo\ndescription: Use when a demo is needed.\n---\n\n# Demo\n\nDo the demo.\n'
const ROLE = '---\nname: judge\ndescription: Use when a judgement is needed.\nmodel_class: strong\neffort: high\ntools: read-only\n---\nBe the judge: "quote" and \\ backslash.\n'
const FULL = '---\nname: driver\ndescription: Use when something must be driven.\nmodel_class: standard\neffort: medium\ntools: full\nneeds_config: deploy_branch\n---\nDrive it.\n'

/** A target repo with .ticketflow/config.json and canonical files. `repo: true` makes it look like the ticketflow repo (canonical in core/). */
function setup({ over = AGENTS, repo = false, skills = { demo: SKILL }, roles = { judge: ROLE, driver: FULL } } = {}) {
    const dir = tempDir('stubs-')
    const put = (p, text) => { mkdirSync(dirname(join(dir, p)), { recursive: true }); writeFileSync(join(dir, p), text) }
    put('.ticketflow/config.json', JSON.stringify(rawConfig(over)))
    const rel = repo ? 'core' : '.ticketflow'
    for (const [n, t] of Object.entries(skills)) put(`${rel}/skills/${n}/SKILL.md`, t)
    for (const [n, t] of Object.entries(roles)) put(`${rel}/agents/${n}.md`, t)
    if (repo) { put('VERSION', '1.2.3\n'); put('skills/init/SKILL.md', 'x'); put('skills/sync/SKILL.md', 'x') }
    return { dir, rel, put, read: (p) => readFileSync(join(dir, p), 'utf8'), has: (p) => existsSync(join(dir, p)) }
}
const run = (t, ...args) => spawnSync(process.execPath, [script, join(t.dir, t.rel), t.dir, ...args], { encoding: 'utf8' })
const rmFile = (t, p) => rmSync(join(t.dir, p))
const MARK = (src) => `<!-- Generated by ticketflow gen-stubs from ${src}. Do not edit: change the source, run gen-stubs. -->`

test('exact output for one skill and one role, for claude and codex', () => {
    const t = setup()
    const r = run(t)
    assert.equal(r.status, 0, r.stderr)
    assert.equal(t.read('.claude/skills/demo/SKILL.md'),
        `---\nname: "demo"\ndescription: "Use when a demo is needed."\n---\n${MARK('skills/demo/SKILL.md')}\n\nRead \`.ticketflow/skills/demo/SKILL.md\` and follow it; it is the whole skill. Your action map: \`.ticketflow/agents-map/claude.md\`.\n`)
    assert.equal(t.read('.agents/skills/demo/SKILL.md'), t.read('.claude/skills/demo/SKILL.md').replace('agents-map/claude.md', 'agents-map/codex.md'))
    assert.equal(t.read('.claude/agents/judge.md'),
        `---\nname: "judge"\ndescription: "Use when a judgement is needed."\nmodel: "opus"\neffort: "high"\ntools: Bash, Read, Grep, Glob, Skill\n---\n${MARK('agents/judge.md')}\n\nYou are the \`judge\` role. Read \`.ticketflow/agents/judge.md\` and follow it; it is your full instruction. Your action map: \`.ticketflow/agents-map/claude.md\`.\n`)
    assert.equal(t.read('.codex/agents/judge.toml'),
        '# Generated by ticketflow gen-stubs from agents/judge.md. Do not edit: change the source, run gen-stubs.\nname = "judge"\ndescription = "Use when a judgement is needed."\nmodel_reasoning_effort = "high"\ndeveloper_instructions = "You are the `judge` role. Read `.ticketflow/agents/judge.md` and follow it; it is your full instruction. Your action map: `.ticketflow/agents-map/codex.md`.\\n"\n')
})


test('validation errors exit 2 with zero writes', () => {
    const bad = {
        'a 301-char description': SKILL.replace('Use when a demo is needed.', 'Use when ' + 'x'.repeat(292)),
        'no "Use when"': SKILL.replace('Use when a demo', 'A demo'),
        'an unknown key': SKILL.replace('---\n\n#', 'extra: 1\n---\n\n#'),
        'a missing key': SKILL.replace('description: Use when a demo is needed.\n', ''),
        'a name that does not match its directory': SKILL.replace('name: demo', 'name: other'),
        'an uppercase name': SKILL.replace('name: demo', 'name: Demo'),
        'no frontmatter': '# Demo\n',
        'a line that is not key: value': SKILL.replace('name: demo', 'name demo'),
        'a control character': SKILL.replace('Do the demo.', 'Do\u0001 the demo.'),
        'a duplicate key': SKILL.replace('name: demo', 'name: demo\nname: demo'),
    }
    for (const [what, text] of Object.entries(bad)) {
        const t = setup({ skills: { demo: text } })
        const r = run(t)
        assert.equal(r.status, 2, what)
        assert.ok(!t.has('.claude'), what)
    }
    for (const [what, role] of Object.entries({ 'model_class': ROLE.replace('strong', 'huge'), 'effort': ROLE.replace('high', 'max'), 'tools': ROLE.replace('read-only', 'some'), 'a missing effort': ROLE.replace('effort: high\n', ''), 'a bad needs_config': FULL.replace('deploy_branch', 'nope'), 'an inherited needs_config key': FULL.replace('deploy_branch', 'constructor'), 'an unknown needs_config key': FULL.replace('needs_config: deploy_branch', 'needs_config: Nope!') })) {
        const t = setup({ roles: { judge: role.includes('name: driver') ? role.replace('name: driver', 'name: judge') : role } })
        assert.equal(run(t).status, 2, what)
        assert.ok(!t.has('.claude'), what)
    }
})


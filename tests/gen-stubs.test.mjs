test('planWrites: the marker must follow the frontmatter directly; a CRLF checkout of a stub is still ours', () => {
    const stub = '---\nname: x\n---\n<!-- Generated by ticketflow gen-stubs from x. -->\nnew\n'
    const plan = planWrites(new Map([['a.md', stub]]), new Map([
        ['own.md', '---\ntitle: mine\n---\ntext\n---\n<!-- Generated by ticketflow gen-stubs from y. -->\n'],
        ['old.md', stub.replaceAll('\n', '\r\n')], ['a.md', stub.replaceAll('\n', '\r\n')],
    ]))
    assert.deepEqual(plan, { write: ['a.md'], remove: ['old.md'], conflicts: [] })
})


/**
 * Generated stubs and plugin manifests. Pure: no file access, so the output is a function of its inputs.
 *
 * A canonical skill or role (`skills/<n>/SKILL.md`, `practices/<n>/SKILL.md`, `agents/<n>.md`) and a domain guide (`docs/agents/<n>.md`) are the only sources. For each agent in the config, `renderStubs`
 * writes a thin file in that agent's own format that points at it (or, with `body: "inline"`, carries it). Every string is validated,
 * then written through JSON.stringify, which is a valid string in both YAML and TOML.
 */

import { posix } from 'node:path'

export class StubError extends Error {
    name = 'StubError'
}

export const MARKER = 'Generated by ticketflow gen-stubs'
const CLASSES = ['strong', 'standard', 'light']
const EFFORTS = ['low', 'medium', 'high', 'xhigh']
const TOOLS = ['read-only', 'full']
const KEYS = { skill: ['name', 'description'], role: ['name', 'description', 'model_class', 'effort', 'tools', 'needs_config'] }
const OPTIONAL = new Set(['needs_config'])
const CONTROL = /[\u0000-\u0008\u000b-\u001f\u007f]/

const fail = (m) => { throw new StubError(m) }

/** `{ name, description, ...role keys, body }` from a canonical file. The frontmatter is `key: value` lines only. */
export function parseCanonical(text, path) {
    const kind = /(^|\/)SKILL\.md$/.test(path) ? 'skill' : 'role'
    if (CONTROL.test(text)) fail(`${path}: control characters are not allowed`)
    const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(text.replaceAll('\r\n', '\n'))
    if (!m) return fail(`${path}: frontmatter missing`)
    const fm = {}
    for (const line of m[1].split('\n')) {
        const kv = /^([a-z_]+): (\S.*)$/.exec(line)
        if (!kv) fail(`${path}: frontmatter line must be "key: value", got ${JSON.stringify(line)}`)
        if (!KEYS[kind].includes(kv[1])) fail(`${path}: unknown frontmatter key ${kv[1]}`)
        if (Object.hasOwn(fm, kv[1])) fail(`${path}: duplicate frontmatter key ${kv[1]}`)
        fm[kv[1]] = kv[2].trim()
    }
    for (const k of KEYS[kind]) if (!Object.hasOwn(fm, k) && !OPTIONAL.has(k)) fail(`${path}: missing frontmatter key ${k}`)
    const parts = path.split('/')
    const expected = kind === 'skill' ? parts.at(-2) : parts.at(-1).replace(/\.md$/, '')
    if (!/^[a-z0-9-]+$/.test(fm.name) || fm.name !== expected) fail(`${path}: name must be ${expected} (lowercase letters, digits and dashes)`)
    if (!fm.description.startsWith('Use when')) fail(`${path}: description must start with "Use when"`)
    if (fm.description.length > 300) fail(`${path}: description is ${fm.description.length} characters, at most 300`)
    if (kind === 'role') {
        if (!CLASSES.includes(fm.model_class)) fail(`${path}: model_class must be one of ${CLASSES.join(', ')}`)
        if (!EFFORTS.includes(fm.effort)) fail(`${path}: effort must be one of ${EFFORTS.join(', ')}`)
        if (!TOOLS.includes(fm.tools)) fail(`${path}: tools must be one of ${TOOLS.join(', ')}`)
        if (fm.needs_config !== undefined && !/^[a-z_]+$/.test(fm.needs_config)) fail(`${path}: needs_config must be a config key`)
    }
    return { ...fm, body: m[2].replace(/^\n+/, '').replace(/\s+$/, '') + '\n' }
}

/**
 * A domain guide (`docs/agents/<name>.md`): frontmatter that is only a `paths:` list of globs, then a body. `{ name, frontmatter, body }`;
 * the frontmatter is returned verbatim, so the rule stub carries exactly what the guide says.
 */
export function parseGuide(text, path) {
    const name = /^(?:.*\/)?([^/]+)\.md$/.exec(path)?.[1]
    if (!name || !/^[a-z0-9-]+$/.test(name)) fail(`${path}: a guide name is lowercase letters, digits and dashes`)
    const t = text.replaceAll('\r\n', '\n')
    if (CONTROL.test(t)) fail(`${path}: control characters are not allowed`)
    const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(t)
    if (!m) return fail(`${path}: frontmatter missing`)
    const [head, ...globs] = m[1].split('\n')
    if (head !== 'paths:' || !globs.length || !globs.every((l) => /^ *- \S/.test(l))) fail(`${path}: the frontmatter must be a "paths:" list ("- <glob>" lines) and nothing else`)
    return { name, frontmatter: m[1], body: m[2].replace(/^\n+/, '').replace(/\s+$/, '') + '\n' }
}

const note = (runtimeRel) => runtimeRel === '.ticketflow' ? ''
    : `In this repository the runtime lives in \`${runtimeRel}/\`: read every \`.ticketflow/<path>\` as \`${runtimeRel}/<path>\`, except \`.ticketflow/config.json\` and \`.ticketflow/custom/\`.\n\n`

const dig = (v, f) => (Array.isArray(v) ? v.map((x) => dig(x, f)) : v !== null && typeof v === 'object' ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, dig(x, f)])) : f(v))
const json = (x) => JSON.stringify(x, null, 2) + '\n'

/** The value of an adapter's target template for `name`; a target must be relative and stay inside the repo. */
export function target(template, name) {
    if (typeof template !== 'string' || template.startsWith('/') || template.split('/').includes('..') || !template.includes('{name}')) fail(`bad adapter target ${template}`)
    return template.replace('{name}', name)
}

/**
 * Everything gen-stubs owns: a sorted Map of path to content. `skills` and `roles` are `parseCanonical` results plus `src`, the
 * canonical path relative to the runtime (`skills/<n>/SKILL.md`, or `practices/<n>/SKILL.md` for an enabled practice). `guides` are
 * `parseGuide` results: an adapter with a `rule` target gets one rule file per guide. `adapters` are the adapter objects for the agents in the config.
 */
/** A guide's relative Markdown links, rewritten from `docs/agents/` to the folder of the rule file it is copied to. */
export function relinkGuide(body, rulePath) {
    return body.replace(/\]\((?![a-z][\w+.-]*:|#|\/)([^)\s#]+)(#[^)\s]*)?\)/gi, (_, path, frag = '') =>
        `](${posix.relative(posix.dirname(rulePath), posix.join('docs/agents', path)) || '.'}${frag})`)
}

export function renderStubs({ skills, roles, adapters, cfg, runtimeRel, version, guides = [] }) {
    const out = new Map()
    const by = (a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0)
    const put = (path, content) => { if (out.has(path)) fail(`two stubs for ${path}`); out.set(path, content) }
    for (const a of adapters) {
        for (const s of [...skills].sort(by)) {
            const map = `Your action map: \`${runtimeRel}/agents-map/${a.name}.md\`.`
            const text = note(runtimeRel) + (a.skill.body === 'inline' ? `${s.body}\n${map}\n` : `Read \`${runtimeRel}/${s.src}\` and follow it; it is the whole skill. ${map}\n`)
            put(target(a.skill.target, s.name), md([['name', s.name], ['description', s.description]], s.src, text))
        }
        if (a.rule) for (const g of [...guides].sort(by)) put(target(a.rule, g.name), `---\n${g.frontmatter}\n---\n<!-- ${MARKER} from docs/agents/${g.name}.md. Do not edit: change the source, run gen-stubs. -->\n\n${relinkGuide(g.body, target(a.rule, g.name))}`)
        for (const r of [...roles].sort(by)) {
            if (r.needs_config && (!Object.hasOwn(cfg, r.needs_config) ? fail(`${r.src}: needs_config ${r.needs_config} is not a config key`) : cfg[r.needs_config] == null)) continue
            const model = cfg.models[a.name]?.[r.model_class] ?? null
            const map = `Your action map: \`${runtimeRel}/agents-map/${a.name}.md\`.`
            const text = note(runtimeRel) + (a.role.body === 'inline' ? `${r.body}\n${map}\n` : `You are the \`${r.name}\` role. Read \`${runtimeRel}/agents/${r.name}.md\` and follow it; it is your full instruction. ${map}\n`)
            const tools = a.role.tools?.[r.tools] ?? null
            put(target(a.role.target, r.name), a.role.format === 'toml'
                ? `# ${MARKER} from ${r.src}. Do not edit: change the source, run gen-stubs.\nname = ${JSON.stringify(r.name)}\ndescription = ${JSON.stringify(r.description)}\n${model === null ? '' : `model = ${JSON.stringify(model)}\n`}model_reasoning_effort = ${JSON.stringify(r.effort)}\ndeveloper_instructions = ${JSON.stringify(text)}\n`
                : md([['name', r.name], ['description', r.description], ...(model === null ? [] : [['model', model]]), ['effort', r.effort]], r.src, text, tools))
        }
        if (runtimeRel !== '.ticketflow') {
            if (!/^\d+\.\d+\.\d+$/.test(version ?? '')) fail('VERSION must be X.Y.Z')
            for (const f of [a.plugin.manifest, a.plugin.marketplace]) put(f.path, json(dig(f.json, (v) => (v === '{version}' ? version : v === '{repo_url}' ? `https://github.com/${cfg.repo}` : v))))
        }
    }
    return new Map([...out].sort(([x], [y]) => (x < y ? -1 : x > y ? 1 : 0)))
}

function md(fields, src, text, tools) {
    const head = fields.map(([k, v]) => `${k}: ${JSON.stringify(v)}`)
    if (tools) head.push(`tools: ${tools}`)
    return `---\n${head.join('\n')}\n---\n<!-- ${MARKER} from ${src}. Do not edit: change the source, run gen-stubs. -->\n\n${text}`
}

// the marker is the first line of a TOML stub, or the line right after the frontmatter of a Markdown one
const marked = (path, content) => new RegExp(`^${path.endsWith('.toml') ? '# ' : '---\\n(?:(?!---\\n)[^\\n]*\\n)*?---\\n<!-- '}${MARKER} from `).test(content.replaceAll('\r\n', '\n'))

/**
 * `expected` and `disk` are Maps of path to content (disk: every file under the adapters' stub paths). Returns what to write,
 * what to remove (marked, no longer expected) and the conflicts (an expected stub that exists without the marker: never overwritten).
 * A file without a marker in `expected` (a JSON manifest) is always ours to write.
 */
export function planWrites(expected, disk) {
    const write = [], remove = [], conflicts = []
    for (const [path, content] of expected) {
        if (!disk.has(path)) write.push(path)
        else if (disk.get(path) === content) continue
        else if (marked(path, content) && !marked(path, disk.get(path))) conflicts.push(path)
        else write.push(path)
    }
    for (const [path, content] of disk) if (!expected.has(path) && marked(path, content)) remove.push(path)
    return { write, remove, conflicts }
}
